# ── 내부 fetch 함수 ──────────────────────────────────────────────────────────

def _fetch_list() -> pd.DataFrame:
    res = requests.get(_LIST_URL, verify=False, timeout=10)
    res.raise_for_status()
    df = pd.DataFrame(res.json()["parkingList"])
    df = df[df["PARKING_ID"] != 9999].copy()
    df = df[[
        "PARKING_ID", "PARKING_NM", "CELL_ADDR_LOAD",
        "PARKING_DIV_NM", "PARKING_GUBUN", "FREE_YN",
        "CELL_CNT", "HNDCAP_CELL_CNT", "LAT", "LNG", "TEL_NO",
    ]].rename(columns={
        "PARKING_ID":      "주차장ID",
        "PARKING_NM":      "주차장명",
        "CELL_ADDR_LOAD":  "도로명주소",
        "PARKING_DIV_NM":  "주차장구분",
        "PARKING_GUBUN":   "운영구분",
        "FREE_YN":         "무료여부",
        "CELL_CNT":        "총주차면",
        "HNDCAP_CELL_CNT": "장애인면",
        "LAT":             "위도",
        "LNG":             "경도",
        "TEL_NO":          "전화번호",
    })
    df["무료여부"] = df["무료여부"].map({"Y": "무료", "N": "유료"})
    df["위도"] = pd.to_numeric(df["위도"], errors="coerce")
    df["경도"] = pd.to_numeric(df["경도"], errors="coerce")
    return df


def _fetch_realtime() -> pd.DataFrame:
    res = requests.get(_RT_URL, verify=False, timeout=10)
    res.raise_for_status()
    df = pd.DataFrame(res.json()["operating"])
    return df[["PARKING_ID", "USE_CNT", "CURRENT_CNT", "OPEN_YN"]].rename(columns={
        "PARKING_ID":  "주차장ID",
        "USE_CNT":     "사용중",
        "CURRENT_CNT": "여유",
        "OPEN_YN":     "운영여부",
    })


# ── 공개 함수 ────────────────────────────────────────────────────────────────

def get_parking() -> pd.DataFrame:
    """전체 주차장 정보 반환 (정적 + 실시간 + 요금구역)."""
    lst = _fetch_list()
    rt  = _fetch_realtime()
    df  = lst.merge(rt, on="주차장ID", how="left")
    df["요금구역"] = df["주차장명"].map(_ZONE_MAP)
    return df[[
        "주차장ID", "주차장명", "도로명주소",
        "주차장구분", "운영구분", "무료여부", "요금구역",
        "총주차면", "사용중", "여유", "장애인면",
        "운영여부", "위도", "경도", "전화번호",
    ]]


def get_available(min_spaces: int = 1) -> pd.DataFrame:
    """여유 공간이 min_spaces면 이상인 운영 중 주차장만 반환."""
    df = get_parking()
    return df[(df["운영여부"] == "Y") & (df["여유"] >= min_spaces)].reset_index(drop=True)


def get_nearby(lat: float, lng: float, top_n: int = 5) -> pd.DataFrame:
    """좌표 기준 가까운 순서로 주차장 반환 (좌표 없는 주차장 제외)."""
    df = get_parking()
    df = df[(df["위도"] > 0) & (df["경도"] > 0) & (df["운영여부"] == "Y")].copy()
    df["거리"] = ((df["위도"] - lat) ** 2 + (df["경도"] - lng) ** 2) ** 0.5
    return df.nsmallest(top_n, "거리").reset_index(drop=True)


def get_fee_info(parking_name: str) -> dict:
    """주차장명으로 요금 정보 조회. 미등재이면 None 반환."""
    zone = _ZONE_MAP.get(parking_name)
    return {"요금구역": zone, **FEE_TABLE[zone]} if zone else None


